def esc(s: str) -> str:
    return html.escape(s, quote=False)


def quiz_block(num: int, question: str, options: list[str], correct: int, explain: str) -> str:
    letters = "ABCD"
    opts = []
    for i, text in enumerate(options):
        attr = ' data-correct="true"' if i == correct else ""
        opts.append(f'      <button class="opt"{attr}>{letters[i]}. {esc(text)}</button>')
    return (
        f'  <div class="quiz" id="q{num}">\n'
        f'    <div class="q">{num} · {esc(question)}</div>\n'
        f'    <div class="opts">\n'
        + "\n".join(opts)
        + "\n    </div>\n"
        f'    <div class="explain">答案 {letters[correct]}。{explain}</div>\n'
        f"  </div>\n"
    )


def case_block(case: dict) -> str:
    asks = "\n".join(f"      <li>{esc(a)}</li>" for a in case["asks"])
    points = "\n".join(f"        <li>{p}</li>" for p in case["points"])
    return (
        f'  <div class="case-prompt" id="{case["id"]}">\n'
        f'    <h3>{esc(case["title"])}</h3>\n'
        f'    <p>{esc(case["stem"])}</p>\n'
        f"    <p><strong>请先自己写，再展开对照：</strong></p>\n"
        f"    <ol>\n{asks}\n    </ol>\n"
        f'    <details class="details">\n'
        f"      <summary>展开参考要点</summary>\n"
        f'      <div class="ans">\n        <ul>\n{points}\n        </ul>\n      </div>\n'
        f"    </details>\n"
        f"  </div>\n"
    )


